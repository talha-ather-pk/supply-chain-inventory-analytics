def title_card(measure, size, color, hide_on=SURFACE):
    v = card(measure, size=1, container=plain_container(
        title=[{"properties": {"show": lit(True), "text": {"expr": mea(measure)}, "fontColor": solid(color),
                               "fontSize": lit(size), "fontFamily": lit(FONT_SB), "alignment": lit("left")}}]))
    v["objects"]["labels"][0]["properties"]["color"] = solid(hide_on)
    return v


def tooltip_cards(p, items, y0, cols_, w_total, h=70):
    w = (w_total - (cols_ - 1) * 8) / cols_
    for i, (mname, label, style) in enumerate(items):
        x, y = 14 + (i % cols_) * (w + 8), y0 + (i // cols_) * (h + 8)
        p.add(f"t{i}", x, y, w, h, card(mname, size=13, title=label, exact=style == "N", millions=style == "M",
                                        container={"padding": [{"properties": {"top": lit(8), "bottom": lit(4),
                                                                               "left": lit(2), "right": lit(2)}}]}))


def bar(vtype, cat, measure, label, title, subtitle, fill=None, sort=None, tooltips=None, precision=1, units=None, objects=None):
    roles = {"Category": [cat], "Y": [(mea(measure), label)]}
    if tooltips:
        roles["Tooltips"] = tooltips
    lab = labels(True, labelPrecision=lit_int(precision), **({"labelDisplayUnits": units} if units else {}))
    obj = {"dataPoint": measure_fill(fill) if fill else [{"properties": {"fill": solid(PRIMARY)}}], "labels": lab}
    obj.update(objects or {})
    return visual(vtype, roles, title=title, subtitle=subtitle, sort=sort or [(mea(measure), "Descending")], objects=obj)


