def top_short_sku():
    """Active SKU with the most weeks short of stock: the default for the drill-through page when opened directly."""
    short, weeks = {}, {}
    with open(ROOT / "data_clean" / "powerbi" / "fact_inventory.csv", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            short[r["sku"]] = short.get(r["sku"], 0) + int(r["short_week"]); weeks[r["sku"]] = weeks.get(r["sku"], 0) + 1
    return max(short, key=lambda k: (short[k], k))


